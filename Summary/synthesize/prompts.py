def load_config_mapping() -> dict:
    """加载同目录下的 config_mapping.json。"""
    path = Path(__file__).resolve().parent / "config_mapping.json"
    return json.loads(path.read_text(encoding="utf-8"))


def _format_mapping_instructions(section: dict) -> str:
    lines = []
    for subsection in section.get("subsections", []):
        sources = ", ".join([s["file"] for s in subsection.get("sources", [])])
        lines.append(f"- key: {subsection['key']}")
        lines.append(f"  title: {subsection['title']}")
        lines.append(f"  expected_sources: {sources}")
    return "\n".join(lines)


def build_subsection_extract_prompt(section_key: str, summary_text: str) -> str:
    mapping = load_config_mapping()
    section = next((s for s in mapping["sections"] if s["section_key"] == section_key), None)
    if not section:
        raise ValueError(f"未找到 section_key={section_key} 的映射配置")
    instr = _format_mapping_instructions(section)
    return EXTRACT_USER_SUBSECTION.substitute(
        section_title=section["section_title"],
        mapping_instructions=instr,
        summary=summary_text,
    )


def build_subsection_write_prompt(
    section: dict,
    subsection: dict,
    bullets: list[str],
    target_words: int,
) -> str:
    bullet_text = "\n".join(f"- {b}" for b in bullets)
    return WRITE_USER_SUBSECTION.substitute(
        section_title=section["title"],
        subsection_title=subsection["title"],
        subsection_index=subsection["index"],
        bullets=bullet_text,
        target_words=target_words,
    )

